import assert from 'node:assert/strict';
import {memoryTransfer,memoryContext,handleMemory,resolveFollowup} from './src/project-memory.js';
const memory=new Map();
const env={TELEGRAM_BOT_TOKEN:'never-share-this-token',BOT_STATE:{get:async(k,t)=>t==='json'?JSON.parse(memory.get(k)||'null'):memory.get(k)||null,put:async(k,v)=>memory.set(k,v),delete:async k=>memory.delete(k)}};
const prepared=await memoryTransfer(env,{action:'prepare'});
assert.ok(prepared.public_key.n);assert.ok(!prepared.public_key.d,'private key never leaves private KV');
const key=await crypto.subtle.generateKey({name:'AES-GCM',length:256},true,['encrypt']);
const iv=crypto.getRandomValues(new Uint8Array(12));
const archive={coverage:'Available user messages and confirmed notes; not a complete platform export',preferences:['Each episode is exactly 60 seconds. No credit without new authorization.'],messages:[{role:'user',content:'کارتونی سه بعدی و کمدی روزمره'},{role:'user',content:'Old approval: never-share-this-token'}]};
const encode=b=>btoa(String.fromCharCode(...new Uint8Array(b)));
const pub=await crypto.subtle.importKey('jwk',prepared.public_key,{name:'RSA-OAEP',hash:'SHA-256'},false,['encrypt']);
const payload={action:'import',key_id:prepared.key_id,iv:encode(iv),data:encode(await crypto.subtle.encrypt({name:'AES-GCM',iv},key,new TextEncoder().encode(JSON.stringify(archive)))),wrapped_key:encode(await crypto.subtle.encrypt('RSA-OAEP',pub,await crypto.subtle.exportKey('raw',key)))};
assert.ok(!JSON.stringify(payload).includes('کارتونی'),'public transport contains ciphertext only');
assert.equal((await memoryTransfer(env,payload)).messages,2);
await assert.rejects(memoryTransfer(env,payload),'one-use key rejects replay');
const context=await memoryContext(env,'کمدی');
assert.match(context,/کمدی/);assert.match(context,/Never replay/);
assert.ok(!memory.get('assistant:project-memory').includes('never-share-this-token'));
assert.equal(resolveFollowup('نتیجه؟',[{role:'user',content:'چرا خطا داد؟'}]),'/diagnose');
assert.equal(resolveFollowup('ادامه بده',[{role:'user',content:'پایتون را اجرا کن'}]),'/diagnose');
assert.equal(resolveFollowup('ادامه بده',[{role:'user',content:'قسمت بعد بساز'}]),'/status','continuation cannot replay production');
assert.equal(resolveFollowup('بله',[{role:'user',content:'مصرف اعتبار'}]),'بله','short reply cannot authorize historical credit');
assert.equal(resolveFollowup('بفرست',[{role:'user',content:'سناریوی قسمت ۷ را بفرست'}]),'/scenario');
assert.match(await handleMemory(env,'/remember ترجیح جدید'),/ثبت شد/);
assert.match(await memoryContext(env),/ترجیح جدید/);
await handleMemory(env,'/forget_memory');
assert.equal(await memoryContext(env),'');
console.log('encrypted one-use private chat import, honest coverage, retrieval, forgetting and non-replaying followups hold');
