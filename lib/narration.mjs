const NARRATION_SAFE_MAP = {
  "یعنی": "به معنای",
  "يعني": "به معنای",
  "جاکت": "ژاکت",
  "واژه": "لغت",
  "عبارتند از": "هستند",
  "عبارتند": "هستند",
};

function sanitizeFa(text) {
  let out = String(text || "");
  for (const [bad, good] of Object.entries(NARRATION_SAFE_MAP)) {
    out = out.replaceAll(bad, good);
  }
  // QC روی — حساسه
  out = out.replaceAll("—", " ").replaceAll("–", " ");
  return out.replace(/\s+/g, " ").trim();
}

